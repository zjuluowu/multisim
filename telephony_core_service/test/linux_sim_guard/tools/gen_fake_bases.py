def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def split_top(params):
    out, depth, cur = [], 0, ""
    for ch in params:
        if ch in "(<{[":
            depth += 1
        elif ch in ")>}]":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [p.strip() for p in out]


def drop_default(param):
    depth = 0
    for i, ch in enumerate(param):
        if ch in "(<{[":
            depth += 1
        elif ch in ")>}]":
            depth -= 1
        elif ch == "=" and depth == 0:
            return param[:i].strip()
    return param.strip()


def param_name(param):
    m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*$", param)
    return m.group(1) if m else None


def pure_virtuals(text, class_name):
    text = strip_comments(text)
    start = re.search(r"class\s+" + class_name + r"\b[^{;]*\{", text)
    if not start:
        raise SystemExit(f"class {class_name} not found")
    body = text[start.end():]
    methods = []
    for m in re.finditer(r"virtual\s+([^;{}]*?)\s*=\s*0\s*;", body):
        decl = " ".join(m.group(1).split())
        open_idx = decl.find("(")
        depth, close_idx = 0, -1
        for i in range(open_idx, len(decl)):
            if decl[i] == "(":
                depth += 1
            elif decl[i] == ")":
                depth -= 1
                if depth == 0:
                    close_idx = i
                    break
        head = decl[:open_idx].strip()
        params = decl[open_idx + 1:close_idx]
        tail = decl[close_idx + 1:].strip()
        name = head.split()[-1]
        ret = head[: -len(name)].strip()
        plist = [drop_default(p) for p in split_top(params)] if params.strip() else []
        methods.append((ret, name, plist, tail))
    return methods


def default_return(ret):
    if ret == "void":
        return ""
    if ret == "bool":
        return "return false;"
    if ret.startswith("sptr<") or ret.startswith("std::shared_ptr<"):
        return "return nullptr;"
    if ret in ("int32_t", "int", "int64_t", "uint32_t", "ErrCode"):
        return "return -1;"
    return "return {};"


def generate(interface, class_name, out_name, request_hook, source):
    methods = pure_virtuals(open(interface).read(), class_name)
    guard = "LSG_GEN_" + out_name.upper().replace(".", "_")
    lines = [HEADER.format(source=source), f"#ifndef {guard}", f"#define {guard}", "",
             f'#include "{os.path.basename(interface)}"', '#include "lsg/unscripted.h"', "",
             "namespace OHOS {", "namespace SimGuard {", "",
             f"class Unscripted{class_name} : public {'Telephony::' if 'Tel' in class_name else ''}{class_name} {{",
             "public:"]
    for ret, name, plist, tail in methods:
        sig = f"    {ret} {name}({', '.join(plist)}){(' ' + tail) if tail else ''} override"
        pnames = [param_name(p) for p in plist]
        response = None
        for p, n in zip(plist, pnames):
            if request_hook and "InnerEvent::Pointer" in p:
                response = n
        slot = "slotId" if "slotId" in pnames else "-1"
        if response:
            body = f"return OnUnscriptedRequest(\"{name}\", {slot}, {response});"
        else:
            dr = default_return(ret)
            body = f"Unscripted::Record(\"{class_name}::{name}\");{(' ' + dr) if dr else ''}"
        lines.append(sig)
        lines.append("    {")
        lines.append(f"        {body}")
        lines.append("    }")
    if request_hook:
        lines += ["", "protected:",
                  "    virtual int32_t OnUnscriptedRequest(",
                  "        const char *name, int32_t slotId, const AppExecFwk::InnerEvent::Pointer &response) = 0;"]
    lines += ["};", "} // namespace SimGuard", "} // namespace OHOS", "", f"#endif /* {guard} */", ""]
    return "\n".join(lines), len(methods)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--production-root", required=True)
    ap.add_argument("--deps-root", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    jobs = [
        (os.path.join(a.production_root, "interfaces/innerkits/include/i_tel_ril_manager.h"), "ITelRilManager",
         "unscripted_tel_ril_manager.h", True, "telephony_core_service interfaces/innerkits/include/i_tel_ril_manager.h"),
        (os.path.join(a.deps_root, "systemabilitymgr_samgr/interfaces/innerkits/samgr_proxy/include/"
                      "if_system_ability_manager.h"), "ISystemAbilityManager", "unscripted_samgr.h", False,
         "systemabilitymgr_samgr interfaces/innerkits/samgr_proxy/include/if_system_ability_manager.h"),
    ]
    stale = False
    for src, cls, out, hook, label in jobs:
        text, n = generate(src, cls, out, hook, label)
        path = os.path.join(a.out, out)
        if a.check:
            if not os.path.exists(path) or open(path).read() != text:
                print("STALE", path)
                stale = True
        else:
            os.makedirs(a.out, exist_ok=True)
            open(path, "w").write(text)
            print(f"{path}: {n} methods")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
