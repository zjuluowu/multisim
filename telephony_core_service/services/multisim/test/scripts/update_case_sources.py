#!/usr/bin/env python3
"""Update the explicit GN list after adding a top-level business case file."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
files = sorted((root / 'cases').glob('*.cpp'))
text = '# Generated by scripts/update_case_sources.py; shared by Host and Device.\n'
text += 'sim_case_root = get_path_info(".", "abspath")\n'
text += 'sim_case_sources = [\n'
text += ''.join('  "$sim_case_root/' + p.name + '",\n' for p in files)
text += ']\n'
target = root / 'cases/sources.gni'
if args.check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit('Case source list is stale; run scripts/update_case_sources.py')
else:
    target.write_text(text)
