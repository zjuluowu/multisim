#!/usr/bin/env python3
"""Generate explicit GN source lists for independently linked SUT slices."""
import argparse
from pathlib import Path
root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
groups = {
 'sim_case_sources': '*.cpp',
 'sim_protocol_case_sources': 'protocol/*.cpp',
 'sim_platform_case_sources': 'platform/*.cpp',
 'sim_capacity_case_sources': 'capacity/capacity_test.cpp',
 'sim_bootstrap_case_sources': 'capacity/bootstrap_test.cpp',
 'sim_primary_entry_case_sources': 'primary_entry/*.cpp',
 'sim_primary_case_sources': 'primary/*.cpp',
 'sim_reference_case_sources': 'query/g2a_query_test.cpp',
 'sim_upstream_case_sources': 'query/g2a_upstream_test.cpp',
}
text = '# Generated by scripts/update_case_sources.py; shared by Host and Device.\n'
text += 'sim_case_root = get_path_info(".", "abspath")\n'
for name,pattern in groups.items():
 text += name+' = [\n'+''.join('  "$sim_case_root/'+p.relative_to(root/'cases').as_posix()+'",\n' for p in sorted((root/'cases').glob(pattern)))+']\n'
target = root/'cases/sources.gni'
if args.check:
 if not target.is_file() or target.read_text()!=text:raise SystemExit('Case source list is stale; run scripts/update_case_sources.py')
elif not target.is_file() or target.read_text()!=text:target.write_text(text)
